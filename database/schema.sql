-- Schema inicial do Portal Esporte Betim.
-- Adicione aqui as tabelas, indices e relacionamentos do banco de dados.

-- Usuários administrativos (autenticação do painel /administrativo.html).
-- Em dev (H2 em memória) essa tabela é criada automaticamente pelo Hibernate
-- (spring.jpa.hibernate.ddl-auto=update) e populada com um usuário admin
-- padrão por DataSeeder.java. Em produção (Postgres/MySQL), crie a tabela
-- a partir deste script e cadastre os usuários reais.
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL, -- hash BCrypt, nunca texto puro
    perfil VARCHAR(50) NOT NULL  -- ex.: ADMIN
);
